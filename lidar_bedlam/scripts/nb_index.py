"""Generate notebooks/README.md, the index of every notebook.

One row per notebook: what it asks, what it concluded, how many checks
are ticked, when it was created, when it last ran, how big it is. Every
column is derived from the notebook itself or from git, so there is
nothing to keep current by hand.

    python3 <module>/scripts/nb_index.py            rewrite the index
    python3 <module>/scripts/nb_index.py --check    report problems only

Stdlib only: an .ipynb is JSON, so nbformat is not needed.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

INDEX = "README.md"
ASSETS = "ipynb-assets"
EXECUTED = ".executed.ipynb"
HEADING = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
VERDICT = re.compile(r"^\*\*Verdict:\*\*[ \t]*(.+?)[ \t]*$", re.MULTILINE)
CHECKED = re.compile(r"^\s*-\s*\[[xX]\]", re.MULTILINE)
UNCHECKED = re.compile(r"^\s*-\s*\[\s\]", re.MULTILINE)
NUMBERED = re.compile(r"^(\d{3})-(.+)$")
BANNER = "<!-- generated by nb_index.py; do not edit by hand -->"
problems: list[str] = []


@dataclass
class Notebook:
    path: Path
    number: str
    title: str
    verdict: str
    ticked: int
    total_checks: int
    created: str
    last_run: str
    ran_headless: bool
    cells: int

    @property
    def asset_name(self) -> str:
        """nb001_lift_splat_depth.py for 001-lift-splat-depth.ipynb."""
        match = NUMBERED.match(self.path.stem)
        if not match:
            return ""
        return f"nb{match.group(1)}_{match.group(2).replace('-', '_')}.py"


def fail(message: str) -> None:
    problems.append(message)
    print(f"  FAIL {message}")


def markdown(nb: dict[str, Any]) -> str:
    out: list[str] = []
    for cell in nb.get("cells", []):
        if cell.get("cell_type") != "markdown":
            continue
        source = cell.get("source", "")
        out.append(source if isinstance(source, str) else "".join(source))
    return "\n".join(out)


def stamp(value: datetime) -> str:
    return value.strftime("%d-%m-%y")


def created(path: Path) -> str:
    """First commit that added the file, else the filesystem birth time."""
    proc = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=%aI", "--", str(path)],
        capture_output=True,
        text=True,
        check=False,
        cwd=path.parent,
    )
    lines = [ln for ln in proc.stdout.splitlines() if ln.strip()]
    if lines:
        return stamp(datetime.fromisoformat(lines[-1]))
    info = path.stat()
    birth = getattr(info, "st_birthtime", info.st_mtime)
    return stamp(datetime.fromtimestamp(birth))


def last_run(path: Path) -> tuple[str, bool]:
    """Newest execution timestamp from the .executed.ipynb sibling.

    VS Code never writes execution timestamps, so a notebook run only
    there has none. The sibling that `nbconvert --execute` produces is
    regenerated wholesale each run, which is why it is read instead of
    the source notebook: a notebook run headlessly once and in VS Code
    afterwards keeps stale timestamps in its own metadata.
    """
    sibling = path.with_name(path.stem + EXECUTED)
    if sibling.is_file():
        try:
            nb = json.loads(sibling.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            nb = {}
        stamps = [
            value
            for cell in nb.get("cells", [])
            if cell.get("cell_type") == "code"
            for value in cell.get("metadata", {}).get("execution", {}).values()
            if isinstance(value, str)
        ]
        if stamps:
            newest = max(stamps)
            parsed = datetime.fromisoformat(newest.replace("Z", "+00:00"))
            return stamp(parsed.astimezone(UTC)), True
    mtime = datetime.fromtimestamp(path.stat().st_mtime)
    return stamp(mtime), False


def read(path: Path) -> Notebook:
    try:
        nb = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        fail(f"{path.name}: not valid JSON")
        nb = {"cells": []}
    text = markdown(nb)
    heading = HEADING.search(text)
    verdict = VERDICT.search(text)
    ticked = len(CHECKED.findall(text))
    unticked = len(UNCHECKED.findall(text))
    run, headless = last_run(path)
    match = NUMBERED.match(path.stem)
    return Notebook(
        path=path,
        number=match.group(1) if match else "???",
        title=heading.group(1) if heading else "(no heading)",
        verdict=verdict.group(1) if verdict else "",
        ticked=ticked,
        total_checks=ticked + unticked,
        created=created(path),
        last_run=run,
        ran_headless=headless,
        cells=len(nb.get("cells", [])),
    )


def audit(books: list[Notebook], root: Path) -> None:
    for book in books:
        name = book.path.name
        if not NUMBERED.match(book.path.stem):
            fail(f"{name}: must start with three digits and a hyphen")
        if book.title == "(no heading)":
            fail(f"{name}: first markdown cell needs a '# ' heading")
        if book.total_checks == 0:
            fail(f"{name}: no '## Checks' boxes")
        # A finished notebook with nothing written down is the exact
        # state the convention exists to prevent.
        if (
            book.total_checks > 0
            and book.ticked == book.total_checks
            and not book.verdict
        ):
            fail(f"{name}: all checks ticked but no '**Verdict:**' line")
        asset = root / ASSETS / book.asset_name
        if book.asset_name and not asset.is_file():
            fail(f"{name}: missing asset {ASSETS}/{book.asset_name}")

    expected = {b.asset_name for b in books if b.asset_name}
    assets = root / ASSETS
    if assets.is_dir():
        for orphan in sorted(assets.glob("nb*.py")):
            if orphan.name not in expected:
                fail(f"{ASSETS}/{orphan.name}: no notebook owns this asset")


def render(books: list[Notebook]) -> str:
    lines = [
        BANNER,
        "",
        "# Notebooks",
        "",
        "| # | Asks | Verdict | Checks | Created | Last run | Cells |",
        "|---|---|---|---|---|---|---|",
    ]
    footnote = False
    for book in books:
        run = book.last_run if book.ran_headless else f"{book.last_run} *"
        footnote = footnote or not book.ran_headless
        lines.append(
            f"| [{book.number}]({book.path.name}) | {book.title} "
            f"| {book.verdict or 'open'} "
            f"| {book.ticked}/{book.total_checks} "
            f"| {book.created} | {run} | {book.cells} |"
        )
    lines.append("")
    if footnote:
        lines += [
            "`*` file mtime, not a run: VS Code records no execution",
            "timestamps, so only a `nbconvert --execute` sibling gives a",
            "real last-run date.",
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report problems and a stale index, change nothing",
    )
    parser.add_argument(
        "--notebooks",
        type=Path,
        default=Path("notebooks"),
        help="the notebooks directory (default: notebooks)",
    )
    args = parser.parse_args()

    root = args.notebooks
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 1

    found = sorted(
        p for p in root.glob("*.ipynb") if not p.name.endswith(EXECUTED)
    )
    if not found:
        print(f"no notebooks in {root}")
        return 0

    books = [read(p) for p in found]
    audit(books, root)
    wanted = render(books)
    index = root / INDEX

    if args.check:
        current = index.read_text(encoding="utf-8") if index.is_file() else ""
        if current != wanted:
            fail(f"{index} is stale: run nb_index.py")
        if problems:
            print(f"\n{len(problems)} problem(s)")
            return 1
        print(f"{len(books)} notebooks, index current")
        return 0

    index.write_text(wanted, encoding="utf-8")
    print(f"wrote {index} ({len(books)} notebooks)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
